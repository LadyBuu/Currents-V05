/**
 * =============================================================================
 * STILL WATERS - SETTLEMENT LAW COMMANDS
 * js/settlement/settlement-law-commands.js
 * =============================================================================
 *
 * CIVIL LAW MUTATION COMMANDS.
 *
 * This file contains the three civil law commands:
 *   - addCivilLaw    : add a new civil law to a settlement
 *   - updateCivilLaw : apply a partial update to an existing law
 *   - removeCivilLaw : remove a civil law from a settlement
 *
 * Each command is one logical transaction:
 *
 *   read canonical
 *     ↓
 *   validate (via SettlementLawRules)
 *     ↓
 *   build candidate (new law / updated law / filtered list)
 *     ↓
 *   commit candidate        (SettlementCommandCommit.commit)
 *     ↓
 *   return structured result
 *
 * The commit helper owns the write / rebuild / persist / publish
 * sequence. This module does not reimplement any part of it.
 *
 * Contract reference: Settlement Architecture Contracts §5 (Missing-Value
 * Semantics), §9 (Rules Contract), §12 (Command Contract), §13
 * (Persistence Contract), §14 (Notification Contract), §32 (Completion
 * Standard).
 *
 * Domain decisions applied:
 *   - Law ids are generated by the command, not accepted from the
 *     caller. The id format is stable and opaque to the caller.
 *   - Duplicate name detection is case-insensitive on trimmed names.
 *     It is performed here, in the command, so that the failure is
 *     reported as a structured result rather than as a rule reason
 *     that the caller must interpret.
 *   - `createdYear` and `updatedYear` are world years (not
 *     timestamps), consistent with §4.3 (Historical) and §24 (Time).
 *     Technical timestamps, if needed by another subsystem, are
 *     recorded separately.
 *   - All three commands write `civilLaws` as a fresh array. They do
 *     not mutate the existing array in place.
 *
 * Time dependency:
 *   window.getCurrentYearSafe, defined in js/core/time.js, aliased to
 *   window.getCurrentYear. The previous version of this file wrapped
 *   time behind window.Time, which does not exist.
 *
 * =============================================================================
 */

(function () {
    'use strict';

    // =========================================================================
    // 1. DEPENDENCIES
    // =========================================================================

    function _getSettlementQueries() {
        return window.SettlementQueries;
    }

    function _getLawQueries() {
        return window.SettlementLawQueries;
    }

    function _getLawRules() {
        return window.SettlementLawRules;
    }

    function _getCommit() {
        return window.SettlementCommandCommit;
    }

    // =========================================================================
    // 2. HELPERS
    // =========================================================================

    function _failure(code, details) {
        return {
            success: false,
            code: code,
            details: details || {}
        };
    }

    function _copyWith(source, overrides) {
        var copy = {};
        for (var key in source) {
            if (!Object.prototype.hasOwnProperty.call(source, key)) continue;
            copy[key] = source[key];
        }
        for (var overrideKey in overrides) {
            if (!Object.prototype.hasOwnProperty.call(overrides, overrideKey)) continue;
            copy[overrideKey] = overrides[overrideKey];
        }
        return copy;
    }

    function _currentYear() {
        if (typeof window.getCurrentYearSafe !== 'function') {
            throw new Error(
                'settlement-law-commands.js requires time.js (getCurrentYearSafe).'
            );
        }
        return window.getCurrentYearSafe();
    }

    /**
     * Generates a new civil law id. Opaque to the caller; stable within a
     * settlement.
     */
    function _generateLawId() {
        return 'civillaw_' + Date.now() + '_' + Math.random().toString(36).substring(2, 10);
    }

    // =========================================================================
    // 3. ADD CIVIL LAW
    // =========================================================================
    //
    // The command:
    //   1. validates the payload via SettlementLawRules.validateNewLaw
    //   2. checks for a duplicate name against the settlement's existing
    //      laws
    //   3. constructs a law record
    //   4. commits the settlement with the new law appended
    //

    /**
     * @param {string} locationId
     * @param {Object} input
     * @returns {Object} structured result
     */
    function addCivilLaw(locationId, input) {
        var settlement = _getSettlementQueries().getSettlementData(locationId);
        if (!settlement) {
            return _failure('SETTLEMENT_NOT_FOUND', { locationId: locationId });
        }

        var validation = _getLawRules().validateNewLaw(input);
        if (!validation.valid) {
            return _failure('INVALID_LAW', { reasons: validation.reasons });
        }

        var normalized = validation.normalized;
        var existingLaws = settlement.civilLaws || [];

        var duplicate = _getLawRules().findDuplicateName(normalized.name, existingLaws);
        if (duplicate.duplicate) {
            return _failure('DUPLICATE_LAW_NAME', {
                name: normalized.name,
                matchId: duplicate.matchId
            });
        }

        var currentYear = _currentYear();

        var law = {
            id: _generateLawId(),
            name: normalized.name,
            type: normalized.type,
            lawCategory: 'civil',
            domain: normalized.domain,
            description: normalized.description,
            severity: normalized.severity,
            crimeMapping: normalized.crimeMapping,
            createdYear: currentYear,
            updatedYear: currentYear,
            notes: normalized.notes
        };

        var candidateLaws = existingLaws.slice();
        candidateLaws.push(law);

        var candidate = _copyWith(settlement, { civilLaws: candidateLaws });

        var publishedEvent = _getCommit().commit(locationId, candidate, {
            type: 'civilLawAdded',
            lawId: law.id,
            lawName: law.name,
            domain: law.domain,
            severity: law.severity
        });

        return {
            success: true,
            locationId: locationId,
            law: law,
            event: publishedEvent
        };
    }

    // =========================================================================
    // 4. UPDATE CIVIL LAW
    // =========================================================================
    //
    // Partial update. Fields not present in `updates` are left unchanged.
    // The law id is not modifiable. Duplicate name detection excludes the
    // law being updated so that the law can keep its own name.
    //

    /**
     * @param {string} locationId
     * @param {string} lawId
     * @param {Object} updates
     * @returns {Object} structured result
     */
    function updateCivilLaw(locationId, lawId, updates) {
        var settlement = _getSettlementQueries().getSettlementData(locationId);
        if (!settlement) {
            return _failure('SETTLEMENT_NOT_FOUND', { locationId: locationId });
        }

        var existingLaws = settlement.civilLaws || [];
        var lawIndex = -1;
        for (var i = 0; i < existingLaws.length; i++) {
            if (existingLaws[i] && existingLaws[i].id === lawId) {
                lawIndex = i;
                break;
            }
        }
        if (lawIndex === -1) {
            return _failure('LAW_NOT_FOUND', { lawId: lawId });
        }

        var validation = _getLawRules().validateLawUpdate(updates);
        if (!validation.valid) {
            return _failure('INVALID_LAW_UPDATE', { reasons: validation.reasons });
        }

        var normalized = validation.normalized;

        // Duplicate name check when a name is being changed.
        if (normalized.name !== undefined) {
            var duplicate = _getLawRules().findDuplicateName(
                normalized.name,
                existingLaws,
                lawId
            );
            if (duplicate.duplicate) {
                return _failure('DUPLICATE_LAW_NAME', {
                    name: normalized.name,
                    matchId: duplicate.matchId
                });
            }
        }

        // Build the updated law by applying changes.
        var existingLaw = existingLaws[lawIndex];
        var updatedLaw = {};
        for (var key in existingLaw) {
            if (!Object.prototype.hasOwnProperty.call(existingLaw, key)) continue;
            updatedLaw[key] = existingLaw[key];
        }

        for (var field in normalized) {
            if (!Object.prototype.hasOwnProperty.call(normalized, field)) continue;

            if (field === 'crimeMapping') {
                // Partial crimeMapping update: merge field-wise.
                var mergedCrimeMapping = {};
                var existingCrimeMapping = existingLaw.crimeMapping || {};
                for (var ck in existingCrimeMapping) {
                    if (!Object.prototype.hasOwnProperty.call(existingCrimeMapping, ck)) continue;
                    mergedCrimeMapping[ck] = existingCrimeMapping[ck];
                }
                for (var nk in normalized.crimeMapping) {
                    if (!Object.prototype.hasOwnProperty.call(normalized.crimeMapping, nk)) continue;
                    mergedCrimeMapping[nk] = normalized.crimeMapping[nk];
                }
                updatedLaw.crimeMapping = mergedCrimeMapping;
            } else {
                updatedLaw[field] = normalized[field];
            }
        }

        updatedLaw.updatedYear = _currentYear();

        var candidateLaws = existingLaws.slice();
        candidateLaws[lawIndex] = updatedLaw;

        var candidate = _copyWith(settlement, { civilLaws: candidateLaws });

        var publishedEvent = _getCommit().commit(locationId, candidate, {
            type: 'civilLawUpdated',
            lawId: lawId,
            lawName: updatedLaw.name,
            changed: normalized
        });

        return {
            success: true,
            locationId: locationId,
            law: updatedLaw,
            changed: normalized,
            event: publishedEvent
        };
    }

    // =========================================================================
    // 5. REMOVE CIVIL LAW
    // =========================================================================

    /**
     * @param {string} locationId
     * @param {string} lawId
     * @returns {Object} structured result
     */
    function removeCivilLaw(locationId, lawId) {
        var settlement = _getSettlementQueries().getSettlementData(locationId);
        if (!settlement) {
            return _failure('SETTLEMENT_NOT_FOUND', { locationId: locationId });
        }

        var existingLaws = settlement.civilLaws || [];
        var lawIndex = -1;
        for (var i = 0; i < existingLaws.length; i++) {
            if (existingLaws[i] && existingLaws[i].id === lawId) {
                lawIndex = i;
                break;
            }
        }
        if (lawIndex === -1) {
            return _failure('LAW_NOT_FOUND', { lawId: lawId });
        }

        var removedLaw = existingLaws[lawIndex];

        var candidateLaws = [];
        for (var j = 0; j < existingLaws.length; j++) {
            if (j === lawIndex) continue;
            candidateLaws.push(existingLaws[j]);
        }

        var candidate = _copyWith(settlement, { civilLaws: candidateLaws });

        var publishedEvent = _getCommit().commit(locationId, candidate, {
            type: 'civilLawRemoved',
            lawId: lawId,
            lawName: removedLaw.name
        });

        return {
            success: true,
            locationId: locationId,
            lawId: lawId,
            lawName: removedLaw.name,
            event: publishedEvent
        };
    }

    // =========================================================================
    // 6. EXPORTS
    // =========================================================================

    window.SettlementLawCommands = Object.freeze({
        addCivilLaw: addCivilLaw,
        updateCivilLaw: updateCivilLaw,
        removeCivilLaw: removeCivilLaw
    });

})();
